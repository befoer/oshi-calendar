// Temporary utility: download self-hosted fonts for offline PWA.
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const OUT_DIR = join(process.cwd(), "public", "fonts");
const CJK_BASE = "https://cdn.jsdelivr.net/npm/lxgw-wenkai-lite-webfont@1.7.0";
const LATIN_BASE = "https://cdn.jsdelivr.net/npm/@fontsource/m-plus-rounded-1c/files";

async function get(url, tries = 4) {
  let last;
  for (let i = 0; i < tries; i++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`${res.status} ${url}`);
      return res;
    } catch (e) {
      last = e;
      await new Promise((r) => setTimeout(r, 400 * (i + 1)));
    }
  }
  throw last;
}

// Run async tasks with limited concurrency to avoid connection resets.
async function pool(items, limit, worker) {
  const queue = [...items];
  const runners = Array.from({ length: Math.min(limit, queue.length) }, async () => {
    while (queue.length) await worker(queue.shift());
  });
  await Promise.all(runners);
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  await mkdir(join(process.cwd(), "src", "styles"), { recursive: true });
  const cssParts = [];

  // --- CJK display font: LXGW WenKai Lite (regular + bold) ---
  for (const weight of ["regular", "bold"]) {
    const name = `lxgwwenkailite-${weight}.css`;
    const css = await (await get(`${CJK_BASE}/${name}`)).text();
    const files = [...new Set([...css.matchAll(/\.\/files\/([\w.-]+\.woff2)/g)].map((m) => m[1]))];
    await pool(files, 6, async (file) => {
      const buf = await (await get(`${CJK_BASE}/files/${file}`)).arrayBuffer();
      await writeFile(join(OUT_DIR, file), Buffer.from(buf));
    });
    cssParts.push(css.replaceAll("./files/", "/fonts/"));
    console.log(`CJK ${weight}: ${files.length} subsets`);
  }

  // --- Latin rounded font: M PLUS Rounded 1c (400/700, latin subset) ---
  const latinFiles = {
    "m-plus-rounded-1c-latin-400-normal.woff2": "400",
    "m-plus-rounded-1c-latin-700-normal.woff2": "700",
  };
  for (const [file, weight] of Object.entries(latinFiles)) {
    const buf = await (await get(`${LATIN_BASE}/${file}`)).arrayBuffer();
    await writeFile(join(OUT_DIR, file), Buffer.from(buf));
    cssParts.push(`@font-face {
  font-family: 'M PLUS Rounded 1c';
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url('/fonts/${file}') format('woff2');
  unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+2074, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD;
}`);
  }

  const header = `/* AUTO-GENERATED by scripts/fetch-fonts.mjs — self-hosted webfonts (offline PWA). */\n`;
  await writeFile(join(process.cwd(), "src", "styles", "fonts.css"), header + cssParts.join("\n"));
  console.log(`done -> public/fonts, css -> src/styles/fonts.css`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});